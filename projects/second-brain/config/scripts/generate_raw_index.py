#!/usr/bin/env python3
"""Generate the raw/ preservation index (schema 2: nodes + edges).

Run from the vault root. Regenerated by the vault-lint pass; the outputs are
never hand-edited. Contract: docs/raw-layout.md § 색인. Format: the vault graph
index design (docs/superpowers/specs/2026-10-24-vault-graph-index-design.md
§ raw 색인 — docs/raw-index.yml 스키마 2).

Outputs
- docs/raw-index.yml      canonical index. Header aggregates (root/lane counts, by_month,
                          orphans, duplicate source URLs, unpaired slack/originals), then
                          `nodes` (key → file, kind; root + snapshot-lane raw md also carry
                          added date and frontmatter source) and `edges`
                          (one `- ["from","to","kind"]` line each at column 0,
                          kind source·ref·wiki·md·embed).
                          Key = sha1(NFC(path)).hex[:12]. Only git-tracked raw paths appear.
- docs/raw-index.md       short human summary: counts, orphans, duplicate source URLs,
                          pointer to the .yml. No per-file listing.
- private/raw-index.yml   the same nodes/edges shape for raw/*.md that git does not track on
                          this machine (personal/local files), the docs referring to them and
                          their source_<lane> claims. private/ is gitignored, so this never
                          reaches the shared vault. Written only when such files exist; a
                          stale copy is removed when they are gone.

Edges come from one pass per document over the corpus (md under wiki/ outputs/ projects/
areas/ that git can see — tracked plus untracked-but-not-ignored — minus EXCLUDED_DIRS):
wiki links, relative md links, embeds, `raw/<name>` text mentions, and frontmatter
source_<lane> keys. raw/ and Clippings/ notes give source_<lane> edges only.

Reads raw/ filenames + frontmatter only; never modifies anything under raw/.
Stdlib only (YAML is emitted by hand; JSON string quoting is valid YAML).
"""

import datetime
import glob
import hashlib
import json
import os
import posixpath
import re
import subprocess
import sys
import unicodedata
from urllib.parse import unquote

# 엣지의 출발 문서(corpus) 최상위 폴더. glob 이 아니라 git 에 보이는 md 만 읽는다 —
# glob 은 gitignore 된 node_modules md 까지 읽어 머신마다 결과가 달랐다(설계 결정 6).
CORPUS_TOPS = ("wiki", "outputs", "projects", "areas")
# knowledge-viewer shared/scope.ts EXCLUDED_DIRS 와 같은 목록. 경로 조각 하나라도 걸리면 뺀다.
EXCLUDED_DIRS = frozenset({
    "node_modules", ".git", ".claude", ".obsidian", ".trash", ".locks",
    "__pycache__", ".venv", "venv", "dist", "build", ".next", ".cache",
})
# 엣지 종류와 같은 (to, from) 안의 정렬 순서. 설계 § 공통 — 엣지 종류.
EDGE_KINDS = ("source", "ref", "wiki", "md", "embed")
# docs/raw-layout.md § 레인 4: 바이너리 원본을 그대로 보존하는 레인.
# 변환된 MD가 source_<lane> frontmatter 키로 원본을 가리킨다 — 짝 판정의 근거는 그 키다.
# 본문에 "raw/pdf/" 문자열이 스치는 문서(스킬 계약서 등)가 많아 corpus 언급으로는
# 짝을 판정할 수 없다.
# 전용 변환 스킬이 있는 레인(pdf·hwp·doc)만 여기 적으면 안 된다 — 보존된 원본은 스킬이
# 만들었든 수동 잉게스트가 만들었든 색인 대상이다. xlsx는 당시 대응 스킬 없이 생긴 레인이라
# 목록에서 빠져 색인·오펀 탐지에 통째로 잡히지 않았다 (2026-09-15, § 레인 5의 2026-09-06과
# 같은 유형의 두 번째 사례).
CONVERSION_LANES = ("pdf", "hwp", "doc", "xlsx")
# docs/raw-layout.md § 레인 5: Slack export에서 스레드 단위로 추출한 Markdown 보존본.
# 루트 파일과 같은 노트 형태라 참조 0건이면 오펀이다 — 짝 판정 키가 따로 없고,
# 루트 파일과 똑같이 corpus가 경로를 언급하거나 링크하는지(들어오는 엣지)로 판정한다.
SLACK_LANE = "slack"
# docs/raw-layout.md § 레인 2: 루트가 재구조화 임계(200)를 넘은 뒤(2026-10-01) 승격 유입이 가장
# 많은 프로젝트의 repo-doc 스냅샷을 raw/<project>/로 분리했다. 루트 스냅샷과 같은 노트라 같은
# raw 노드(유입일·source·엣지·오펀·URL 중복)로 "raw/<project>/<file>" 경로로 싣고, 루트 파일
# 수에서만 뺀다. 기존 루트 스냅샷은 append-only라 옮기지 않는다.
# 어느 프로젝트를 레인으로 둘지는 볼트마다 달라서 team-settings.yaml `raw.snapshot_lanes`가 정한다.
SETTINGS_PATH = "projects/second-brain/config/team-settings.yaml"
ROOT_CAP_HINT = 300  # docs/raw-layout.md § 하지 않기로 한 것: 다음 재검토 임계 (200 → 300, 2026-10-01)
YML_PATH = "docs/raw-index.yml"
MD_PATH = "docs/raw-index.md"
PRIVATE_YML_PATH = "private/raw-index.yml"

# git's default core.quotepath=true octal-escapes every non-ASCII path in
# --name-only output, so Korean/smart-punctuation filenames never matched the
# os.listdir names and were reported as "untracked" on machines with the default
# config (2026-09-03, 34 files). Force quotepath off and normalize to NFC on both sides.
GIT = ["git", "-c", "core.quotepath=false"]


def fail(msg: str) -> None:
    sys.exit(f"generate_raw_index: {msg}")


def nfc(s: str) -> str:
    return unicodedata.normalize("NFC", s)


def read_snapshot_lanes(path: str) -> tuple:
    """team-settings.yaml 최상위 `raw:` 아래의 `snapshot_lanes: ["a", "b"]` 한 줄(JSON 흐름
    리스트)만 읽는다. 다른 부모 아래의 같은 이름 키는 보지 않는다.

    키가 없으면 레인 없음. 두 번 정의됐거나 그 모양이 아니면 실패한다 — 조용히 비면 그 레인이
    색인·오펀 탐지에서 통째로 빠진다(docs/raw-layout.md § 레인 2).
    """
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    except FileNotFoundError:
        return ()
    in_raw, found = False, []
    for line in lines:
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            in_raw = re.match(r"raw:\s*(#.*)?$", line) is not None
            continue
        m = re.match(r"\s+snapshot_lanes:(.*)$", line) if in_raw else None
        if m:
            found.append(m.group(1))
    if not found:
        return ()
    if len(found) > 1:
        fail(f"{path}: raw.snapshot_lanes is defined {len(found)} times")
    try:
        lanes = json.loads(found[0].split(" #")[0].strip())
    except ValueError:
        lanes = None
    if not (isinstance(lanes, list)
            and all(isinstance(x, str) and re.fullmatch(r"[a-z0-9][a-z0-9-]*", x) for x in lanes)):
        fail(f'{path}: snapshot_lanes must be a one-line list like ["my-app"]')
    return tuple(lanes)


SNAPSHOT_LANES = read_snapshot_lanes(SETTINGS_PATH)


def indexed_name(path: str) -> "str | None":
    """raw/<file>.md → "<file>.md"; raw/<snapshot-lane>/<file>.md → "<lane>/<file>.md"; else None."""
    if not (path.startswith("raw/") and path.endswith(".md")):
        return None
    rest = path[4:]
    if "/" not in rest:
        return rest
    lane, _, name = rest.partition("/")
    if lane in SNAPSHOT_LANES and "/" not in name:
        return rest
    return None


def first_add_dates() -> dict:
    """First date each current indexed raw path entered raw/.

    A move into raw/ (from Clippings/) counts as an add. A rename inside raw/ (an approved
    filename fix, docs/raw-layout.md § Append-only) keeps the old path's date.
    """
    out = subprocess.run(
        GIT + ["log", "--reverse", "--find-renames", "--diff-filter=AR",
               "--name-status", "--format=@%ad", "--date=short", "--", "raw/"],
        capture_output=True, text=True, encoding="utf-8",
    ).stdout
    dates, current = {}, None
    for line in out.splitlines():
        if line.startswith("@"):
            current = line[1:]
            continue
        parts = line.split("\t")
        if len(parts) == 2 and parts[0] == "A" and indexed_name(parts[1]):
            dates.setdefault(nfc(indexed_name(parts[1])), current)
        elif len(parts) == 3 and parts[0].startswith("R") and indexed_name(parts[2]):
            old = indexed_name(parts[1])
            dates.setdefault(nfc(indexed_name(parts[2])), dates.get(nfc(old), current) if old else current)
    return dates


def tracked_raw() -> set:
    out = subprocess.run(GIT + ["ls-files", "--", "raw/"], capture_output=True, text=True, encoding="utf-8").stdout
    return {nfc(indexed_name(l)) for l in out.splitlines() if indexed_name(l)}


def tracked_lane_files(lane: str) -> list:
    """Tracked files directly under raw/<lane>/ — subdirectories do not count.

    raw/doc/media/<stem>/ holds images extracted from a .docx, not preserved
    originals (docs/raw-layout.md § 레인 4), so only the lane's own level counts.
    """
    prefix = f"raw/{lane}/"
    out = subprocess.run(GIT + ["ls-files", "--", prefix], capture_output=True, text=True, encoding="utf-8").stdout
    return sorted(nfc(l) for l in out.splitlines()
                  if l.startswith(prefix) and "/" not in l[len(prefix):])


# 위키링크 [[대상|별칭]]·임베드 ![[…]]. 대상은 첫 | 앞, 첫 # 앞, 끝 \ 제거(표 칸 안의 \|).
WIKI_RE = re.compile(r"(!?)\[\[([^\[\]\n]+?)\]\]")
# 상대 링크 [라벨](url)·이미지 ![…](url). url 은 <…> 꼴이거나 첫 공백 앞(제목 제외).
MDLINK_RE = re.compile(r"(!?)\[[^\]\n]*\]\(([^)\n]*)\)")
SCHEME_RE = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")
SOURCE_LANE_RE = re.compile(
    r'^(?:' + "|".join(f"source_{lane}" for lane in CONVERSION_LANES)
    + r'):\s*"?([^"\n]+?)"?\s*$', re.M)
SOURCE_RE = re.compile(r'^source:\s*"?([^"\n]+?)"?\s*$', re.M)


def visible_md(tops: tuple) -> list:
    """md under the given top folders that git can see — tracked plus untracked-not-ignored.

    Returns sorted (open path, NFC vault path) pairs. A path with any segment in
    EXCLUDED_DIRS is dropped (case-insensitive, like the viewer's scope.ts).
    """
    out = subprocess.run(
        GIT + ["ls-files", "-co", "--exclude-standard", "-z", "--", *tops],
        capture_output=True,
    ).stdout.decode("utf-8", "surrogateescape")
    seen = {}
    for path in out.split("\0"):
        if not path.endswith(".md"):
            continue
        if any(seg.lower() in EXCLUDED_DIRS for seg in path.split("/")):
            continue
        seen.setdefault(nfc(path), path)
    return sorted((p, n) for n, p in seen.items())


def read_text(path: str) -> "str | None":
    try:
        with open(path, encoding="utf-8") as fh:
            return nfc(fh.read())
    except (OSError, UnicodeDecodeError):
        return None


def frontmatter(text: str) -> str:
    """The leading --- block (text prefix, so offsets match); "" when there is none.

    An unclosed block falls back to the first 3000 characters, as the earlier
    frontmatter readers did.
    """
    if not text.startswith("---"):
        return ""
    end = text.find("\n---", 3)
    return text[:end] if end != -1 else text[:3000]


def source_claims(text: str) -> list:
    """(line start offset, value) per frontmatter source_<lane> key of a converted note.

    raw/·Clippings/·corpus 의 변환 MD 가 원본을 가리키는 짝 판정 키다. 변환 스킬은
    원본을 raw/<lane>/ 에 보존하고 변환 MD 를 Clippings/ 에 쓴다. ingest 가 raw/ 로
    옮기기 전까지 짝은 Clippings/ 에 있다 — raw/ 만 보면 그 사이에 원본이 오펀으로
    잡힌다(ingest 스킬은 clippings 를 옮기기 전에 따로 커밋한다).
    """
    return [(text.rfind("\n", 0, m.start()), nfc(m.group(1).strip()))
            for m in SOURCE_LANE_RE.finditer(frontmatter(text))]


def node_key(path: str) -> str:
    """Node key shared with the viewer link cache: sha1(NFC(path)).hex[:12]."""
    return hashlib.sha1(nfc(path).encode("utf-8")).hexdigest()[:12]


class RawNodes:
    """Every raw node path (raw/…), with names bucketed by the two chars after raw/."""

    def __init__(self, paths) -> None:
        self.paths = set(paths)
        self.buckets = {}
        for p in sorted(self.paths):
            name = p[4:]
            self.buckets.setdefault(name[:2], []).append(name)


def scan_doc(src: str, text: str, raw: RawNodes, originals: set, add) -> None:
    """One pass over a corpus document: links, embeds, mentions, source_<lane> claims."""
    folder = posixpath.dirname(src)
    linked = set()  # (줄 시작 위치, raw 노드) — 같은 줄의 언급은 ref 로 세지 않는다
    for m in WIKI_RE.finditer(text):
        target = m.group(2).split("|", 1)[0].split("#", 1)[0].rstrip("\\").strip()
        if not target.startswith("raw/"):
            continue  # 경로 없는 이름은 raw 로 해석하지 않는다(설계 결정 9)
        node = target if target in raw.paths else target + ".md"
        if node in raw.paths:
            add(src, node, "embed" if m.group(1) else "wiki")
            linked.add((text.rfind("\n", 0, m.start(2)), node))
    for m in MDLINK_RE.finditer(text):
        url = m.group(2).strip()
        url = url[1:].split(">", 1)[0] if url.startswith("<") else (url.split() or [""])[0]
        if not url or url.startswith(("#", "/", "\\")) or SCHEME_RE.match(url):
            continue
        node = posixpath.normpath(posixpath.join(folder, unquote(url.split("#", 1)[0])))
        if node in raw.paths:
            add(src, node, "embed" if m.group(1) else "md")
            linked.add((text.rfind("\n", 0, m.start(2)), node))
    claimed_lines = set()
    for line, value in source_claims(text):
        claimed_lines.add(line)
        if value in originals:
            add(src, value, "source")
    pos = text.find("raw/")
    while pos != -1:
        at = pos + 4
        for name in raw.buckets.get(text[at:at + 2], ()):
            if text.startswith(name, at):
                node = "raw/" + name
                if linked or claimed_lines:
                    line = text.rfind("\n", 0, pos)
                    if line in claimed_lines or (line, node) in linked:
                        continue
                add(src, node, "ref")
        pos = text.find("raw/", at)


def y(s) -> str:
    """YAML scalar: JSON quoting is a valid YAML double-quoted string."""
    return json.dumps(s, ensure_ascii=False)


def emit_graph(rows: list, edges: set) -> list:
    """nodes + edges sections. rows: ordered (path, kind, extra fields) per node.

    Edge order: to-node order → from path → kind (EDGE_KINDS). A key collision
    inside one file fails instead of silently merging two paths.
    """
    keys, order = {}, {}
    for i, (path, _, _) in enumerate(rows):
        k = node_key(path)
        if keys.setdefault(k, path) != path:
            fail(f"node key collision {k}: {keys[k]!r} and {path!r}")
        order[path] = i
    lines = ["nodes:" + (" {}" if not rows else "")]
    for path, kind, extra in rows:
        fields = [("file", path), ("kind", kind)] + extra
        lines.append(f"  {y(node_key(path))}: {{"
                     + ", ".join(f"{f}: {y(v)}" for f, v in fields) + "}")
    lines.append("edges:" + (" []" if not edges else ""))
    for f, t, kind in sorted(edges, key=lambda e: (order[e[1]], e[0], EDGE_KINDS.index(e[2]))):
        # 링크 캐시와 같은 꼴: 0 열 블록 항목 + 공백 없는 JSON 배열(파일 크기를 줄인다).
        lines.append(f"- [{y(node_key(f))},{y(node_key(t))},{y(kind)}]")
    return lines


def doc_rows(edges: set, node_paths: set) -> list:
    """doc nodes — edge sources that are not raw nodes themselves, by path."""
    return [(p, "doc", []) for p in sorted({f for f, _, _ in edges} - node_paths)]


def main() -> None:
    if not (os.path.isdir("raw") and os.path.isfile("VAULT_RULES.md")):
        fail("run from the vault root (raw/ + VAULT_RULES.md required)")

    raws = [nfc(f) for f in os.listdir("raw") if f.endswith(".md")]
    for lane in SNAPSHOT_LANES:
        if os.path.isdir(f"raw/{lane}"):
            raws += [f"{lane}/{nfc(f)}" for f in os.listdir(f"raw/{lane}") if f.endswith(".md")]
    raws.sort()
    shots = len(glob.glob("raw/screenshots/**/*.*", recursive=True))
    originals = {lane: tracked_lane_files(lane) for lane in CONVERSION_LANES}
    originals_total = sum(len(v) for v in originals.values())
    original_paths = sorted(p for lane in CONVERSION_LANES for p in originals[lane])
    original_set = set(original_paths)
    slack = tracked_lane_files(SLACK_LANE)

    added = first_add_dates()
    tracked = tracked_raw()
    raw = RawNodes(["raw/" + n for n in raws] + slack + original_paths)
    untracked = {"raw/" + n for n in raws if n not in tracked}

    edges = set()
    add = lambda f, t, kind: edges.add((f, t, kind))

    # raw/ 와 Clippings/ 의 변환 MD 는 짝(source) 엣지만 낸다. raw 노트는 frontmatter source 도 읽는다.
    entries, private_entries, sources = [], [], {}
    for name in raws:
        path = "raw/" + name
        text = read_text(path) or ""
        m = SOURCE_RE.search(text[:3000]) if text.startswith("---") else None
        src = m.group(1).strip() if m else ""
        for _, value in source_claims(text):
            if value in original_set:
                add(path, value, "source")
        entry = {"name": name, "source": src}
        if name in tracked:
            entry["added"] = added.get(name, "unknown")
            entries.append(entry)
            if src:
                sources.setdefault(src, []).append(name)
        else:
            entry["added"] = "untracked"
            private_entries.append(entry)
    if original_set:
        for open_path, path in visible_md(("Clippings",)):
            if "/" in path[len("Clippings/"):]:
                continue
            text = read_text(open_path)
            for _, value in source_claims(text or ""):
                if value in original_set:
                    add(path, value, "source")

    for open_path, path in visible_md(CORPUS_TOPS):
        text = read_text(open_path)
        if text and "raw/" in text:
            scan_doc(path, text, raw, original_set, add)

    # 집계는 엣지에서 낸다. 미추적 raw 의 엣지도 짝 집계에는 센다.
    incoming = {}
    for _, t, kind in edges:
        incoming.setdefault(t, set()).add(kind)
    orphans = [e["name"] for e in entries
               if not incoming.get("raw/" + e["name"], set()) - {"source"}]
    orphan_slack = [p for p in slack if not incoming.get(p)]
    orphan_originals = [p for lane in CONVERSION_LANES for p in originals[lane]
                        if "source" not in incoming.get(p, ())]

    root_count = sum(1 for e in entries if "/" not in e["name"])
    snapshot_counts = {lane: sum(1 for e in entries if e["name"].startswith(lane + "/"))
                       for lane in SNAPSHOT_LANES if os.path.isdir(f"raw/{lane}")}
    dup_urls = {u: fs for u, fs in sources.items()
                if len(fs) > 1 and u.startswith("http")}
    by_month = {}
    for e in entries:
        by_month[e["added"][:7]] = by_month.get(e["added"][:7], 0) + 1

    # 공유 파일에는 미추적 raw 경로가 나오지 않는다 — 그 엣지는 private 파일에만(설계 결정 11).
    shared_edges = {e for e in edges if e[0] not in untracked and e[1] not in untracked}
    private_edges = edges - shared_edges
    raw_rows = [("raw/" + e["name"], "raw", [("added", e["added"]), ("source", e["source"])])
                for e in sorted(entries, key=lambda e: (e["added"], e["name"]), reverse=True)]
    raw_rows += [(p, "raw", []) for p in slack]
    raw_rows += [(p, "raw", []) for p in original_paths]
    raw_rows += doc_rows(shared_edges, raw.paths)

    today = datetime.date.today().isoformat()

    # --- docs/raw-index.yml (canonical) ---
    yml = [
        "# Raw Index — raw/ 보존소의 자동 생성 색인. 수동 편집 금지.",
        "# 재생성: vault 루트에서 python3 projects/second-brain/config/scripts/generate_raw_index.py",
        "# 계약: docs/raw-layout.md § 색인. 형식: docs/superpowers/specs/2026-10-24-vault-graph-index-design.md",
        "schema: 2",
        f"generated: {y(today)}",
        f"root_files: {root_count}",
        f"root_cap: {ROOT_CAP_HINT}",
        f"screenshots: {shots}",
        "by_month:" + (" {}" if not by_month else ""),
    ]
    if snapshot_counts:
        # 레인 디렉터리가 없는 vault에서는 절을 쓰지 않는다(slack·변환 원본과 같은 규칙).
        snap_yml = ["snapshot_files:"] + [f"  {lane}: {n}" for lane, n in snapshot_counts.items()]
        yml[-1:] = snap_yml + [yml[-1]]
    if slack:
        # 레인이 없는 vault에서는 절을 쓰지 않는다 — 0으로 채운 절은 diff 잡음만 늘린다
        # (변환 원본 레인과 같은 규칙).
        slack_yml = [f"slack_files: {len(slack)}",
                     "orphan_slack:" + (" []" if not orphan_slack else "")]
        slack_yml += [f"  - {y(p)}" for p in orphan_slack]
        yml[-1:] = slack_yml + [yml[-1]]
    if originals_total:
        # 레인 디렉터리가 아직 없는 vault에서는 이 절을 아예 쓰지 않는다 — 0으로 채운
        # 절이 색인마다 붙으면 diff 잡음만 늘고 읽는 쪽에 알려주는 것이 없다.
        lane_yml = ["conversion_originals:"]
        lane_yml += [f"  {lane}: {len(originals[lane])}" for lane in CONVERSION_LANES]
        lane_yml.append("orphan_originals:" + (" []" if not orphan_originals else ""))
        lane_yml += [f"  - {y(p)}" for p in orphan_originals]
        yml[-1:] = lane_yml + [yml[-1]]
    if by_month:
        yml += [f"  {y(m)}: {n}" for m, n in sorted(by_month.items(), reverse=True)]
    yml.append("orphans:" + (" []" if not orphans else ""))
    yml += [f"  - {y('raw/' + n)}" for n in orphans]
    yml.append("duplicate_sources:" + (" []" if not dup_urls else ""))
    for url, files in sorted(dup_urls.items()):
        yml.append(f"  - url: {y(url)}")
        yml.append("    files:")
        yml += [f"      - {y('raw/' + n)}" for n in files]
    yml += emit_graph(raw_rows, shared_edges)
    yml.append("")
    with open(YML_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(yml))

    # --- docs/raw-index.md (summary only) ---
    md = [
        "# Raw Index",
        "",
        "`raw/` 보존소의 자동 생성 색인 요약 — **수동 편집 금지.** 파일별 상세(유입일·source)와 파생 노트 연결(nodes·edges)은",
        f"`{YML_PATH}`에 있다. 재생성: vault 루트에서 `python3 projects/second-brain/config/scripts/generate_raw_index.py`",
        "(`vault-lint` 패스가 실행). 계약: `docs/raw-layout.md` § 색인.",
        "",
        f"- 생성: {today} · 루트 파일 {root_count} (서브폴더 재구조화 임계 {ROOT_CAP_HINT})"
        + "".join(f" · {lane} 레인 {n}" for lane, n in snapshot_counts.items())
        + f" · screenshots 레인 {shots}개 항목"
        + (f" · slack 레인 {len(slack)}" if slack else "")
        + (" · 변환 원본 "
           + "·".join(f"{lane} {len(originals[lane])}" for lane in CONVERSION_LANES)
           if originals_total else ""),
        f"- 오펀(참조 0건): {len(orphans)} · source URL 중복: {len(dup_urls)}",
        "- 월별 유입: " + " · ".join(f"{m} {n}" for m, n in sorted(by_month.items(), reverse=True)),
    ]
    if orphans:
        md += ["", "## 오펀 — lint 리포트 대상", ""]
        md += [f"- `raw/{n}`" for n in orphans]
    if orphan_slack:
        md += ["", "## slack 레인 오펀 — lint 리포트 대상", "",
               "어느 노트도 경로를 언급하거나 링크하지 않는 Slack 추출본이다.", ""]
        md += [f"- `{p}`" for p in orphan_slack]
    if orphan_originals:
        md += ["", "## 변환 원본 짝 없음 — lint 리포트 대상", "",
               "변환된 MD의 `source_<lane>` frontmatter 키가 가리키지 않는 보존 원본이다."
               " 변환이 누락됐거나 키가 빠졌다.", ""]
        md += [f"- `{p}`" for p in orphan_originals]
    if dup_urls:
        md += ["", "## source URL 중복 — lint 리포트 대상", ""]
        for url, files in sorted(dup_urls.items()):
            md.append(f"- {url}")
            md += [f"  - `raw/{n}`" for n in files]
    md.append("")
    with open(MD_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(md))

    # --- private/raw-index.yml (this machine's untracked raw files only) ---
    if private_entries:
        os.makedirs("private", exist_ok=True)
        rows = [("raw/" + e["name"], "raw", [("added", e["added"]), ("source", e["source"])])
                for e in sorted(private_entries, key=lambda e: e["name"], reverse=True)]
        claimed = {t for _, t, _ in private_edges if t in original_set}
        rows += [(p, "raw", []) for p in original_paths if p in claimed]
        rows += doc_rows(private_edges, raw.paths)
        pv = [
            "# 이 머신에서 git이 추적하지 않는 raw/*.md — 개인/로컬 파일. private/는 gitignored.",
            "# generate_raw_index.py가 재생성한다. 공유 색인(docs/raw-index.yml)에는 실리지 않는다.",
            "schema: 2",
            f"generated: {y(today)}",
            f"untracked_files: {len(private_entries)}",
        ]
        pv += emit_graph(rows, private_edges)
        pv.append("")
        with open(PRIVATE_YML_PATH, "w", encoding="utf-8") as fh:
            fh.write("\n".join(pv))
    elif os.path.isfile(PRIVATE_YML_PATH):
        os.remove(PRIVATE_YML_PATH)

    kinds = {k: sum(1 for e in shared_edges if e[2] == k) for k in EDGE_KINDS}
    print(f"{YML_PATH} + {MD_PATH} written: {len(entries)} tracked files, "
          f"{len(raw_rows)} nodes, {len(shared_edges)} edges ("
          + " ".join(f"{k} {n}" for k, n in kinds.items()) + "), "
          f"{len(orphans)} orphans, {len(dup_urls)} duplicate URLs"
          + (f"; {originals_total} conversion originals, "
             f"{len(orphan_originals)} unpaired" if originals_total else "")
          + (f"; {len(private_entries)} untracked → {PRIVATE_YML_PATH}" if private_entries else ""))


if __name__ == "__main__":
    main()
